-- NutriPath PostgreSQL schema (user data only).
-- Applied by initDB.js (run before the server by `npm start`); every statement is idempotent.
-- Reference data (foods, recipes, supplements, interaction rules) lives in data.js.
--
-- Timestamps are stored as UTC text "YYYY-MM-DD HH24:MI:SS" (the frontend parses that format);
-- log dates are "YYYY-MM-DD" in APP_TZ, computed by the app.

-- Accounts: one row per Firebase (Google) user, or per demo sign-in when Firebase is not configured
CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firebase_uid  TEXT NOT NULL UNIQUE,
  email         TEXT,
  name          TEXT NOT NULL,
  photo_url     TEXT,
  provider      TEXT NOT NULL DEFAULT 'google',      -- google | demo
  onboarded     INTEGER NOT NULL DEFAULT 0,          -- 0 until /api/users/setup completes
  email_opt_in  INTEGER NOT NULL DEFAULT 1,          -- daily 8 AM summary email
  created_at    TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  last_login_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

-- Schema-drift repair: a `users` table created by an older version of the app keeps its old
-- shape (CREATE TABLE IF NOT EXISTS never alters it), which makes the login upsert in db.js
-- fail with a 500. Bring every column the INSERT / RETURNING uses up to date.
ALTER TABLE users ADD COLUMN IF NOT EXISTS email         TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS photo_url     TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS provider      TEXT NOT NULL DEFAULT 'google';
ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarded     INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_opt_in  INTEGER NOT NULL DEFAULT 1;
ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at    TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS');
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS');
-- Rows inserted with explicit ids (e.g. a data import) leave the identity sequence behind,
-- so the next sign-up collides on the primary key. Move it past the current maximum.
SELECT setval(pg_get_serial_sequence('users', 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM users), 1),
              (SELECT COUNT(*) > 0 FROM users));

CREATE TABLE IF NOT EXISTS health_profiles (
  user_id              INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  age                  INTEGER NOT NULL DEFAULT 25 CHECK (age > 0 AND age < 120),
  sex                  TEXT NOT NULL DEFAULT 'male' CHECK (sex IN ('male', 'female')),
  height_cm            DOUBLE PRECISION NOT NULL DEFAULT 170,
  weight_kg            DOUBLE PRECISION NOT NULL DEFAULT 65,
  activity_level       TEXT NOT NULL DEFAULT 'light',      -- sedentary | light | moderate | active | very_active
  goal                 TEXT NOT NULL DEFAULT 'maintain',   -- lose | maintain | recomp | gain
  diet_type            TEXT NOT NULL DEFAULT 'vegetarian', -- vegetarian | eggetarian | non-veg | vegan
  conditions           TEXT NOT NULL DEFAULT '[]',         -- JSON array, e.g. ["diabetes","pcos"]
  medications          TEXT NOT NULL DEFAULT '[]',         -- JSON array
  allergies            TEXT NOT NULL DEFAULT '[]',         -- JSON array
  appliances           TEXT NOT NULL DEFAULT '[]',         -- JSON array: kettle, induction
  living_setup         TEXT NOT NULL DEFAULT 'hostel',     -- hostel | pg | home
  mess_menu            TEXT,
  monthly_food_budget  INTEGER,
  daily_calorie_target INTEGER,
  daily_water_target   INTEGER NOT NULL DEFAULT 8,
  updated_at           TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

-- One row per user per day: water + synced activity (calories eaten are summed from meal_logs)
CREATE TABLE IF NOT EXISTS daily_logs (
  user_id          INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  log_date         TEXT NOT NULL,                    -- YYYY-MM-DD in APP_TZ
  water_glasses    INTEGER NOT NULL DEFAULT 0,
  steps            INTEGER,
  calories_burned  INTEGER,
  active_minutes   INTEGER,
  sync_source      TEXT,                             -- google_fit | apple_health
  synced_at        TEXT,
  PRIMARY KEY (user_id, log_date)
);

-- Every food the user logs (barcode, AI photo, mess menu, meal plan, manual)
CREATE TABLE IF NOT EXISTS meal_logs (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  log_date   TEXT NOT NULL,
  name       TEXT NOT NULL,
  quantity   TEXT,                                   -- e.g. "150 g", "1 katori"
  kcal       DOUBLE PRECISION NOT NULL DEFAULT 0,
  protein_g  DOUBLE PRECISION NOT NULL DEFAULT 0,
  carbs_g    DOUBLE PRECISION NOT NULL DEFAULT 0,
  fat_g      DOUBLE PRECISION NOT NULL DEFAULT 0,
  source     TEXT NOT NULL DEFAULT 'manual',         -- manual | barcode | ai_photo | ai_menu | meal_plan | recipe
  barcode    TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_meal_logs_user_date ON meal_logs (user_id, log_date);

CREATE TABLE IF NOT EXISTS meal_plans (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  focus       TEXT,
  meals       TEXT NOT NULL,                         -- JSON
  total_kcal  INTEGER,
  created_at  TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS chatbot_history (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role        TEXT NOT NULL CHECK (role IN ('user', 'model')),
  message     TEXT NOT NULL,
  created_at  TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_chat_user ON chatbot_history (user_id, id);

-- Lab results entered in the Lab Analyzer (B12, ferritin, Vitamin D, haemoglobin…)
CREATE TABLE IF NOT EXISTS health_observations (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  observed_on     TEXT NOT NULL,
  metric          TEXT NOT NULL,
  value           DOUBLE PRECISION NOT NULL,
  unit            TEXT,
  reference_range TEXT,
  status          TEXT
);
CREATE INDEX IF NOT EXISTS idx_obs_user ON health_observations (user_id, observed_on);

-- Illness Recovery Roadmap checklist state (Day 1–14)
CREATE TABLE IF NOT EXISTS recovery_checks (
  user_id  INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plan     TEXT NOT NULL,                            -- viral_cold | food_poisoning
  day      INTEGER NOT NULL CHECK (day BETWEEN 1 AND 14), -- first day of the phase (1, 4 or 8)
  item     INTEGER NOT NULL,
  done_at  TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (user_id, plan, day, item)
);

-- Hostel / mess menu items read from a menu photo by Gemini Vision (Diet Planner → Hostel Menu)
CREATE TABLE IF NOT EXISTS hostel_menus (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  meal       TEXT,                                   -- breakfast | lunch | snacks | dinner | any
  quantity   TEXT,
  kcal       DOUBLE PRECISION NOT NULL DEFAULT 0,
  protein_g  DOUBLE PRECISION NOT NULL DEFAULT 0,
  carbs_g    DOUBLE PRECISION NOT NULL DEFAULT 0,
  fat_g      DOUBLE PRECISION NOT NULL DEFAULT 0,
  tip        TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_hostel_menus_user ON hostel_menus (user_id, id);

-- "My Journey" gamified 7-day roadmap: the day the user is on (1–7; 8 = journey complete)
CREATE TABLE IF NOT EXISTS journey_progress (
  user_id      INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  current_day  INTEGER NOT NULL DEFAULT 1 CHECK (current_day BETWEEN 1 AND 8),
  updated_at   TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

-- Daily summary emails sent (cron + test button)
CREATE TABLE IF NOT EXISTS email_log (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id   INTEGER REFERENCES users(id) ON DELETE CASCADE,
  kind      TEXT NOT NULL,                           -- daily | test
  to_addr   TEXT NOT NULL,
  status    TEXT NOT NULL,                           -- sent | logged | failed
  detail    TEXT,
  sent_at   TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

